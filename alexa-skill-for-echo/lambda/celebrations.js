// Checkbox celebrations: the portal's confetti, as the Roku plays it
// (CelebrationBurst.brs, MainScene onCelebrate/playFinale/spawnBurst) and
// tvOS (Celebrations.swift, DisplayController.playFinale). Ticking a box
// bursts confetti on it; completing a whole list adds the finale - six
// bigger bursts from the left and right bands of the upper half, 210ms
// apart. The painted portal never bakes its own confetti into a capture;
// the device is the only one celebrating.
//
// The burst is the Roku's own pre-filmed sheet (images/celebrations/
// burst.png, tools/generate-celebrations.js), played once through a
// frame-sized window - effect-all.js's MmFxSheet layout, so those layouts
// must be in the document too. The Lambda cannot serve the sheet and it is
// too big (~480 KB) to travel in the document like the spinner, so it is
// hosted and named by CELEBRATION_URL; without it there are no
// celebrations (layer, commands and definitions come back empty).
//
// Everything is on the screen from the start, invisible:
//   mmCelB          the box burst (380 canvas px), moved to the box by
//                   its holder mmCelAt's bound translate (mmCelX/mmCelY,
//                   dp of its centre)
//   mmCelF0..F5     the finale bursts (560 px) at fixed band positions,
//                   drawn per document from a seeded generator (the Roku
//                   draws new ones per finale; a document cannot)
// and two named commands (document `commands`) play them, so a checkbox
// carries one short command instead of seven sequences:
//   MmCelebrate(kind, x, y)   kind "burst" | "finale" (or an expression
//                             giving one); x, y: the box centre in dp
//   MmCelebratePlay(slot)     one slot: show, step the frames once, hide
// Each slot plays on its own sequencer (celebrations-<slot>), so a press
// returns at once and a new press restarts only that slot.

const { rng, sheetWindow } = require("./effect-all");

// source/celebrationMap.brs (generated by tools/generate-celebrations.js;
// keep in step when the sheet is filmed again)
const BURST = { frameW: 409, frameH: 409, frameCount: 24, cols: 5, rows: 5, frameMs: 70 };
const BOX_PX = 380;
const FINALE_PX = 560;
const FINALE_N = 6;
const FINALE_STAGGER_MS = 210;
const SLOT_B = "mmCelB";
const HOLDER = "mmCelAt";
const slotF = (i) => "mmCelF" + i;

const sheetUrl = () => process.env.CELEBRATION_URL || "";
const r1 = (v) => Math.round(v * 10) / 10;

/** The bursts, all invisible, in a full-screen container placed once
 * above everything (including the effects and the busy spinner).
 * ctx = { place, canvas, vp } as for effects. */
function layer(ctx) {
  const url = sheetUrl();
  if (!url) return [];
  const { place, canvas, vp } = ctx;
  const s = place.len(BOX_PX);
  const items = [{
    // centred on (mmCelX, mmCelY): the holder sits centred on the origin.
    // Not on the sheet itself: an instance's `bind` would replace the
    // layout's own (mmFxF)
    type: "Container", id: HOLDER, position: "absolute", left: r1(-s / 2), top: r1(-s / 2), width: r1(s), height: r1(s),
    bind: [{ name: "mmCelX", value: 0 }, { name: "mmCelY", value: 0 }],
    transform: [{ translateX: "${mmCelX}" }, { translateY: "${mmCelY}" }],
    items: [sheetWindow(SLOT_B, url, BURST, s, s, 0, 0, false, { opacity: 0 })],
  }];
  // the Roku's bands: x 190-570 px in from either side, y 55-485 px; one
  // window size for every slot (one play command), finale ones scaled up
  const rand = rng("finale" + canvas.width + "x" + canvas.height);
  for (let i = 0; i < FINALE_N; i++) {
    let x = rand() * 380 + 190;
    if (i % 2 === 1) x = canvas.width - x;
    const y = rand() * 430 + 55;
    items.push(sheetWindow(slotF(i), url, BURST, s, s, place.ox + place.len(x) - s / 2, place.oy + place.len(y) - s / 2, false, {
      opacity: 0,
      transform: [{ scale: Math.round((FINALE_PX / BOX_PX) * 1000) / 1000 }],
    }));
  }
  return [{ type: "Container", position: "absolute", left: 0, top: 0, width: vp.w, height: vp.h, items }];
}

/** The document's named commands (merge into the doc's opts.commands). */
function commandDefinitions() {
  if (!sheetUrl()) return {};
  const set = (id, property, value) => ({ type: "SetValue", componentId: id, property, value });
  // a slot on its own sequencer, after `wait` ms (Idle: a command's own
  // `delay` is not honoured from an event handler, APL docs)
  const onSlot = (slot, wait) => ({
    type: "Sequential", sequencer: "celebrations-" + slot,
    commands: (wait ? [{ type: "Idle", delay: wait }] : []).concat({ type: "MmCelebratePlay", slot }),
  });
  return {
    MmCelebratePlay: {
      parameters: ["slot"],
      commands: [
        set("${slot}", "opacity", 1),
        // one pass of the sheet (MmFxSheet's cycle position)
        {
          type: "AnimateItem", componentId: "${slot}", duration: BURST.frameCount * BURST.frameMs,
          value: [{ property: "mmFxF", from: 0, to: 1 }],
        },
        set("${slot}", "opacity", 0),
      ],
    },
    MmCelebrate: {
      parameters: ["kind", "x", "y"],
      commands: [
        set(HOLDER, "mmCelX", "${x}"),
        set(HOLDER, "mmCelY", "${y}"),
        // on the box first, so the press is answered at once
        onSlot(SLOT_B, 0),
        {
          type: "Sequential", when: "${kind == 'finale'}",
          commands: [...Array(FINALE_N).keys()].map((i) => onSlot(slotF(i), i * FINALE_STAGGER_MS)),
        },
      ],
    },
  };
}

/** What a checkbox press runs once it has ticked the box. info = { kind:
 * "burst" | "finale" or an APL expression giving one, x, y: the box
 * centre in dp, numbers or expressions }. */
function commandsFor(info) {
  if (!sheetUrl() || !info) return [];
  const kind = info.kind === undefined ? "burst" : info.kind;
  // numbers, or expressions (a layout's own parameters)
  const at = (v) => (typeof v === "string" ? v : r1(Number(v) || 0));
  return [{ type: "MmCelebrate", kind, x: at(info.x), y: at(info.y) }];
}

// ---- "is the whole list done?" on the device -------------------------
// InteractionLayer.listComplete: a list is the boxes of one widget on the
// page; todos split further per project. The screen counts each list's
// open boxes in a root variable mmOpen<n>; a press moves its list's count
// and reads it for the kind. A box knows its list by number (a layout
// parameter), and APL cannot name a variable from a value, so the count
// commands and the kind are written once over every list, picking theirs
// with `when` / a conditional.

/** A target's list identity (widget, plus project for todos). */
function listKey(item, pageIndex) {
  const clean = (v) => String(v == null ? "" : v).replace(/[^0-9A-Za-z]/g, "");
  const proj = item && item.kind === "todo" ? "_" + clean(item.payload && item.payload.projectId) : "";
  return pageIndex + "_" + clean(item && item.widgetSettingId) + proj;
}

/** The screen's lists. pages: the manifest's; states[p]: checked per
 * target of page p (touch.applyOverrides(...).states). Returns
 *   binds              root variables mmOpen<n> = open boxes (also what an
 *                      in-place update sets on the root)
 *   index(p, item)     the box's list number (its layout parameter)
 *   onTick(param, id)  commands for the box after its tick: its list's
 *                      count one down when now ticked, up when unticked
 *                      (reads mmTicked); id: the root's component id
 *   kind(param)        the kind for commandsFor, read after onTick */
function lists(pages, states) {
  const keys = [];
  const open = [];
  (pages || []).forEach((page, p) => {
    const items = (page && page.targets && page.targets.items) || [];
    items.forEach((it, i) => {
      const k = listKey(it, p);
      if (!keys.includes(k)) {
        keys.push(k);
        open.push(0);
      }
      if (!(states && states[p] && states[p][i] === true)) open[keys.indexOf(k)] += 1;
    });
  });
  const name = (n) => "mmOpen" + n;
  return {
    binds: open.map((value, n) => ({ name: name(n), value })),
    index: (p, item) => keys.indexOf(listKey(item, p)),
    onTick: (param, rootId) => keys.map((_, n) => ({
      type: "SetValue", componentId: rootId, when: "${" + param + " == " + n + "}",
      property: name(n), value: "${" + name(n) + " + (mmTicked ? -1 : 1)}",
    })),
    kind: (param) => {
      if (!keys.length) return "burst";
      const pick = keys.map((_, n) => n).reduceRight((rest, n) => param + " == " + n + " ? " + name(n) + " : " + rest, "1");
      return "${(" + pick + ") <= 0 ? 'finale' : 'burst'}";
    },
  };
}

module.exports = { layer, commandsFor, commandDefinitions, lists, listKey, BURST, BOX_PX, FINALE_PX };
